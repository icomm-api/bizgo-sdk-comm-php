<?php

declare(strict_types=1);

namespace Bizgo\Resource;

use Bizgo\Exception\ApiException;
use Bizgo\Exception\ConnectionException;
use Bizgo\Exception\InvalidResponseException;
use Bizgo\Exception\ValidationException;
use Bizgo\Http\Multipart;
use Bizgo\Http\Transport;
use Bizgo\Model\BrandMessageFileUploadResponse;
use Bizgo\Model\BrandMessageFileUploadResult;
use Bizgo\Model\FileUploadResponse;
use Bizgo\Model\FileUploadResult;
use Bizgo\Model\RcsFileUploadResponse;
use Bizgo\Model\RcsFileUploadResult;
use Bizgo\Model\ResponseModel;
use Bizgo\Upload;

/**
 * Image uploads: `POST /api/comm/v1/file/*`. Access as `$client->files`.
 *
 * `$file` is a local path (string or `SplFileInfo`), an open stream resource, or an {@see Upload}
 * (`Upload::fromContents($bytes, 'banner.jpg')` for bytes you already have). The file is read once and the
 * same bytes are reused if the upload is retried. Uploads are retried only on HTTP 429.
 *
 * The other upload operations of the spec (brand message catalog images, AlimTalk template images) are generated
 * methods of this class ({@see FilesOperations}).
 */
final class Files
{
    use FilesOperations;

    /** MMS images: jpg, at most 300KB. Checked before sending. */
    public const MMS_MAX_BYTES = 300 * 1024;

    /** Brand message image kinds. Each has its own size and ratio rules (see the API reference). */
    public const BRAND_KINDS = ['default', 'wide', 'wideItemList', 'wideItemList/first', 'carouselFeed', 'carouselCommerce'];

    /** operationId of each brand message image kind. Catalog images: {@see self::uploadBrandMessageCatalog()}. */
    private const BRAND_OPERATIONS = [
        'default' => 'uploadBrandMessageDefaultImage',
        'wide' => 'uploadBrandMessageWideImage',
        'wideItemList' => 'uploadBrandMessageWideItemListImage',
        'wideItemList/first' => 'uploadBrandMessageWideItemListFirstImage',
        'carouselFeed' => 'uploadBrandMessageCarouselFeedImage',
        'carouselCommerce' => 'uploadBrandMessageCarouselCommerceImage',
    ];

    /** @internal */
    public function __construct(private readonly Transport $transport)
    {
    }

    /**
     * Uploads an MMS image (jpg, max 300KB). Use `$result->fileKey` in `MmsMessage::$fileKey`.
     *
     * @param string|\SplFileInfo|Upload|resource $file
     * @param string|null $filename name sent to the server (default: the file's name)
     * @param string|null $fileKey your own key for the file (default: generated by the server)
     * @param string|null $imageName image name (default: the file name without extension)
     *
     * @throws ValidationException the file is larger than 300KB or cannot be read
     * @throws ApiException
     * @throws ConnectionException
     * @throws InvalidResponseException
     */
    public function uploadMms(
        #[\SensitiveParameter]
        mixed $file,
        ?string $filename = null,
        ?string $fileKey = null,
        ?string $imageName = null,
    ): FileUploadResult {
        $upload = Upload::from($file, $filename);
        if (strlen($upload->contents) > self::MMS_MAX_BYTES) {
            throw ValidationException::of('file', 'MMS 이미지는 최대 300KB입니다(jpg, 권장 1,500×1,440px 이하)');
        }
        $response = $this->upload('uploadMmsFile', FileUploadResponse::class, $upload, $fileKey, $imageName);

        return $response->data->data ?? new FileUploadResult();
    }

    /**
     * Uploads an RCS image. Use `$result->media` in `RcsBody::$media`.
     *
     * @param string|\SplFileInfo|Upload|resource $file
     *
     * @throws ValidationException
     * @throws ApiException
     * @throws ConnectionException
     * @throws InvalidResponseException
     */
    public function uploadRcs(
        #[\SensitiveParameter]
        mixed $file,
        ?string $filename = null,
        ?string $fileKey = null,
        ?string $imageName = null,
    ): RcsFileUploadResult {
        $response = $this->upload('uploadRcsFile', RcsFileUploadResponse::class, Upload::from($file, $filename), $fileKey, $imageName);

        return $response->data->data ?? new RcsFileUploadResult();
    }

    /**
     * Uploads a Kakao brand message image. Use `$result->imgUrl` in the message.
     *
     * @param string|\SplFileInfo|Upload|resource $file
     * @param string $kind one of {@see self::BRAND_KINDS}; anything else is refused before sending
     *
     * @throws ValidationException
     * @throws ApiException
     * @throws ConnectionException
     * @throws InvalidResponseException
     */
    public function uploadBrandMessage(
        #[\SensitiveParameter]
        mixed $file,
        string $kind = 'default',
        ?string $filename = null,
        ?string $fileKey = null,
        ?string $imageName = null,
    ): BrandMessageFileUploadResult {
        if (!in_array($kind, self::BRAND_KINDS, true)) {
            throw ValidationException::of('kind', '지원하지 않는 브랜드메시지 이미지 종류입니다 (' . implode(', ', self::BRAND_KINDS) . ')');
        }
        $response = $this->upload(
            self::BRAND_OPERATIONS[$kind],
            BrandMessageFileUploadResponse::class,
            Upload::from($file, $filename),
            $fileKey,
            $imageName,
        );

        return $response->data->data ?? new BrandMessageFileUploadResult();
    }

    /**
     * @template T of ResponseModel
     *
     * @param class-string<T> $response
     *
     * @return T
     *
     * @throws ApiException
     * @throws ConnectionException
     * @throws InvalidResponseException
     * @throws ValidationException
     */
    private function upload(string $operationId, string $response, Upload $upload, ?string $fileKey, ?string $imageName): ResponseModel
    {
        $form = Multipart::build('file', $upload, ['fileKey' => $fileKey, 'imageName' => $imageName]);

        return $this->transport->call($operationId, $response, multipart: $form);
    }
}
